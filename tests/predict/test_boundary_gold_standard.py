@pytest.mark.parametrize("clock_name", sorted(boundary_gold_standard_dict))
def test_boundary_predictions_match_gold(clock_name):
    np.testing.assert_allclose(
        predict_at_boundaries(clock_name),
        boundary_gold_standard_dict[clock_name],
        rtol=0,
        atol=0.01,
    )


def test_every_shipped_clock_is_pinned():
    """A new clock must arrive with boundary expectations, not silently unpinned."""
    shipped = sorted(path.stem for path in WEIGHTS_DIR.glob("*.pt"))
    if not shipped:
        pytest.skip(f"{WEIGHTS_DIR} is build output; generate it by running the clock notebooks")
    assert shipped == sorted(boundary_gold_standard_dict)
