"""Gold-standard predictions at the edges of every feature's plausibility range.

``test_gold_standard.py`` pins each clock's prediction on one seeded random row.
This suite pins two more rows per clock: every feature at its registered lower
bound, and every feature at its registered upper bound. Random inputs land in
the middle of a clock's arithmetic; boundary inputs land where transforms
divide by zero, saturate, or overflow, so the two suites fail differently and
the pair catches more than either alone.

The rows are deliberately extreme. Registry bounds are *plausibility* bounds
chosen to catch unit errors, so a boundary row can be physiologically absurd
(creatinine at 3000 µmol/L, every methylation site at exactly 0). Four clocks
therefore predict ``nan`` or ``inf`` here; those values are pinned as such,
with the reason, rather than skipped — a boundary that stops being non-finite
is a change in a clock's arithmetic and this suite should say so.

Predictions come from ``clocks/weights/*.pt`` rather than from
``pya.pred.load_clock``, so that the values pinned here are the clocks this
release ships rather than whatever is currently published on HuggingFace.
"""

